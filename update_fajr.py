days_in_month = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

# Build lookup
fajr_lookup = {}
for day_idx, row in enumerate(openfajr_raw):
    day = day_idx + 1
    for month_idx, time_val in enumerate(row):
        month = month_idx + 1
        if time_val is not None and day <= days_in_month[month_idx]:
            fajr_lookup[(month, day)] = time_val

print(f"OpenFajr entries: {len(fajr_lookup)}")

# Update both city files
for city in ['birmingham', 'london']:
    with open(f"data_{city}.json") as f:
        data = json.load(f)

    updated = []
    changed = 0
    for entry in data:
        m, d = entry['month'], entry['day']
        new_entry = {
            'month': m,
            'day': d,
            'dawn': fajr_lookup.get((m, d), entry['dawn']),
            'sunrise': entry['sunrise'],
            'noon': entry['noon'],
            'sunset': entry['sunset'],
            'maghrib': entry['maghrib'],
            'midnight': entry['midnight']
        }
        if new_entry['dawn'] != entry['dawn']:
            changed += 1
        updated.append(new_entry)

    with open(f"data_{city}.json", 'w') as f:
        json.dump(updated, f)

    print(f"{city}: {len(updated)} days, {changed} fajr times changed from najaf->openfajr")

